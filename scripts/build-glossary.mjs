#!/usr/bin/env node
/**
 * Generates src/data/glossary.ts from scripts/scraped.json (run scrape.mjs first).
 * Text is migrated verbatim apart from whitespace normalisation and the small
 * typo list below (each fix is logged so it can be reported to the client).
 * Usage: node scripts/build-glossary.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** [search, replace] typo fixes — meaning unchanged. */
const FIXES = [
  [/\bheath insurance\b/g, "health insurance"],
  [/\bHM0s\b/g, "HMOs"],
  [/\brehabilitiation\b/g, "rehabilitation"],
  [/ {2,}/g, " "],
];

const slugify = (s) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

async function main() {
  const { glossary } = JSON.parse(await readFile(path.join(ROOT, "scripts", "scraped.json"), "utf8"));
  const fixed = [];
  const fix = (s, where) => {
    let out = s;
    for (const [re, rep] of FIXES) out = out.replace(re, (m) => {
      if (m.trim()) fixed.push(`${where}: "${m}" → "${rep}"`);
      return rep;
    });
    return out.trim();
  };

  const entries = glossary.flatMap((g) =>
    g.entries.map((e) => ({
      id: slugify(e.term),
      letter: g.letter.toUpperCase(),
      term: fix(e.term, e.term),
      definition: fix(e.definition, e.term),
    })),
  );
  const notice = glossary.find((g) => g.notice)?.notice.replace(/^NOTICE:\s*/, "") ?? "";

  const ts = `/**
 * Insurance glossary — migrated verbatim from the legacy site
 * (businessinsurancewashingtondc.com/glossary/a/ … /w/; X, Y, Z were empty).
 * GENERATED by scripts/build-glossary.mjs — do not edit by hand.
 */

export type GlossaryEntry = {
  /** URL-safe anchor id, e.g. "actual-cash-value" */
  id: string;
  /** Upper-case initial letter, A–Z */
  letter: string;
  /** Term as written on the legacy site (upper case) */
  term: string;
  /** Definition; "\\n\\n" separates paragraphs, "\\n" separates list lines */
  definition: string;
};

/** Legal disclaimer shown under the glossary on the legacy site — keep verbatim. */
export const glossaryNotice = ${JSON.stringify(notice)};

export const glossary: GlossaryEntry[] = ${JSON.stringify(entries, null, 2)};
`;
  await writeFile(path.join(ROOT, "src", "data", "glossary.ts"), ts);
  console.log(`Wrote ${entries.length} glossary entries.`);
  if (fixed.length) console.log("Typo fixes:\n  " + fixed.join("\n  "));
}

main();
